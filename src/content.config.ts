/**
 * What each kind of content file must contain. If a file breaks these rules,
 * the build stops and names the file and the field, so mistakes never reach the live site.
 */
import { defineCollection, reference } from 'astro:content';
import { file, glob } from 'astro/loaders';
import { z } from 'astro/zod';
import { roles } from './content/people/roles';
import { publicationSchema } from './lib/publication-schema';

/** PubMed IDs, written as plain numbers: [38500596, 38466836] */
const pmids = z.array(z.coerce.string()).default([]);

/** A single file in src/content/pages/. */
const page = (name: string) => glob({ pattern: `${name}.md`, base: './src/content/pages' });

/** src/content/themes/*.md: one file per research theme; the text below the --- is its summary. */
const themes = defineCollection({
  loader: glob({ pattern: '*.md', base: './src/content/themes' }),
  schema: z.object({
    name: z.string(),
    /** Position on the Home and Research pages: 1 comes first. */
    order: z.number(),
  }),
});

/** src/content/research/*.md: one file per project. */
const research = defineCollection({
  loader: glob({ pattern: '*.md', base: './src/content/research' }),
  schema: ({ image }) =>
    z.object({
      title: z.string(),
      /** The theme's file name, e.g. genome-maintenance */
      theme: reference('themes'),
      /** Position within its theme: 1 comes first. */
      order: z.number(),
      /** Path to the figure, relative to the project file, e.g. ./figures/rpa.png */
      figure: image().optional(),
      /** Describes the figure; also read aloud by screen readers. */
      caption: z.string(),
      /** 2–3 key papers for this project. */
      keyPapers: pmids,
    }),
});

/** src/content/people/current/*.md: one file per current lab member; the text below the --- is their bio. */
const members = defineCollection({
  loader: glob({ pattern: '*.md', base: './src/content/people/current' }),
  schema: ({ image }) =>
    z.object({
      name: z.string(),
      /** One of the roles in src/content/people/roles.ts; sets their position on the People page. */
      role: z.enum(roles),
      /** Path to a square headshot, relative to this file, e.g. ./photos/jane-doe.jpg */
      photo: image().optional(),
      email: z.email().optional(),
    }),
});

/** src/content/people/alumni/*.md: one file per former member. */
const alumni = defineCollection({
  loader: glob({ pattern: '*.md', base: './src/content/people/alumni' }),
  schema: z.object({
    name: z.string(),
    /** Their role while in the lab, e.g. "Postdoctoral Fellow". */
    role: z.string(),
    /** The years they joined and left, e.g. from: 2015 and to: 2020 */
    from: z.int(),
    to: z.int(),
    /** Where they are now, e.g. "Assistant Professor, University of Somewhere". */
    nowAt: z.string(),
  }),
});

/** src/content/pages/home.md: the text below the --- is the mission sentence. */
const home = defineCollection({
  loader: page('home'),
  schema: ({ image }) =>
    z.object({
      /** The large home-page figure, e.g. ./home-figure.png */
      figure: image().optional(),
      /** Describes the figure; also read aloud by screen readers. */
      caption: z.string(),
      /** Papers to feature on the home page. Leave [] to show the most recent ones. */
      featuredPapers: pmids,
    }),
});

/** src/content/pages/contact.md: contact details; the text below the --- is "Joining the lab". */
const contact = defineCollection({
  loader: page('contact'),
  schema: z.object({
    email: z.email(),
    /** Each line of the mailing address, top to bottom. */
    address: z.array(z.string()).min(1),
    /** A Google Maps or Apple Maps link. Leave it out to hide the Directions link. */
    directionsUrl: z.url().optional(),
  }),
});

/** src/data/publications.json: generated by `npm run publications`; never edit by hand. */
const publications = defineCollection({
  loader: file('src/data/publications.json'),
  schema: publicationSchema,
});

export const collections = { themes, research, members, alumni, home, contact, publications };
